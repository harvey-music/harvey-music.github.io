-- ============================================================
-- Arthur 工作室 · 账号体系 + 留言板（第一期）
-- 文件 01 / 04：表结构、索引、约束、触发器
--
-- 用法：Supabase 控制台 → SQL Editor → New query → 整段粘贴 → Run
-- 特点：可重复执行（所有对象都带 if not exists / or replace）
-- 说明：不依赖 citext 等扩展，全部用内置类型 + 表达式唯一索引，
--       避免扩展装在别的 schema 时 PostgREST 找不到类型的问题。
-- ============================================================

-- ---------- 1. 用户资料 ----------
-- auth.users 客户端读不到，所以昵称/简介必须另存一张表。
-- 注意：这张表里绝对不能出现 is_admin 之类的权限字段 ——
--       本人能改自己这一行，放权限字段就等于把提权接口开放出去。
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  username    text        not null,
  bio         text        not null default '',
  trust_level smallint    not null default 0,
  is_banned   boolean     not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),

  constraint profiles_username_len   check (char_length(username) between 3 and 20),
  constraint profiles_username_trim  check (username = btrim(username)),
  constraint profiles_username_no_at check (position('@' in username) = 0),
  constraint profiles_username_space check (username !~ '[[:space:]]'),
  constraint profiles_username_chars check (username !~ '[<>"&/\\;%*]'),
  constraint profiles_username_reserved check (
    lower(username) <> all (array[
      'admin', 'administrator', 'moderator', 'root', 'system', 'support',
      'arthur', '站长', '管理员', '官方', '客服', '小编'
    ])
  ),
  constraint profiles_bio_len     check (char_length(bio) <= 200),
  constraint profiles_trust_range check (trust_level between 0 and 1)
);

-- 昵称不区分大小写唯一：Arthur 和 arthur 视为同一个人
create unique index if not exists profiles_username_lower_uidx
  on public.profiles (lower(username));

-- ---------- 2. 留言 ----------
-- status 只有触发器能改；客户端即使硬塞 published 也会被改写回待审。
create table if not exists public.messages (
  id           bigint generated by default as identity primary key,
  author_id    uuid        not null,
  body         text        not null,
  status       text        not null default 'pending',
  created_at   timestamptz not null default now(),
  published_at timestamptz,
  reviewed_by  uuid,
  reviewed_at  timestamptz,
  deleted_at   timestamptz,
  deleted_by   uuid,
  delete_reason text,
  author_ip    inet,
  author_ua    text,

  -- 外键名写死，前端 PostgREST 内联查询要用到这个名字
  constraint messages_author_fkey   foreign key (author_id)   references public.profiles (id) on delete cascade,
  constraint messages_reviewer_fkey foreign key (reviewed_by) references public.profiles (id) on delete set null,
  constraint messages_deleter_fkey  foreign key (deleted_by)  references public.profiles (id) on delete set null,

  constraint messages_body_len   check (char_length(body) between 1 and 1000),
  constraint messages_body_trim  check (body = btrim(body)),
  constraint messages_status_chk check (status in ('pending', 'published', 'rejected', 'withdrawn', 'deleted'))
);

create index if not exists messages_board_idx  on public.messages (status, created_at desc);
create index if not exists messages_author_idx on public.messages (author_id, created_at desc);

-- ---------- 3. 角色 ----------
-- 站长身份只在这里，profiles 里没有。客户端读不到别人的行，
-- 判权一律走 private.is_admin()（security definer），不靠前端。
create table if not exists public.user_roles (
  user_id    uuid        not null references auth.users (id) on delete cascade,
  role       text        not null,
  granted_by uuid        references auth.users (id) on delete set null,
  granted_at timestamptz not null default now(),

  primary key (user_id, role),
  constraint user_roles_role_chk check (role in ('admin', 'moderator'))
);

-- ---------- 4. 敏感词 ----------
-- severity = 'block' 直接拒绝发布；'flag' 只降级为待审。
-- 这张表对客户端完全不可见（开 RLS 且不给任何策略）。
create table if not exists public.banned_words (
  id         bigint generated by default as identity primary key,
  word       text        not null,
  severity   text        not null default 'block',
  created_at timestamptz not null default now(),

  constraint banned_words_sev_chk check (severity in ('block', 'flag')),
  constraint banned_words_len     check (char_length(word) between 1 and 60)
);

create unique index if not exists banned_words_lower_uidx
  on public.banned_words (lower(word));

-- ---------- 5. 操作日志 ----------
-- 只由 RPC 写入，站长可读。出事时能查到"谁在什么时候动了哪条"。
create table if not exists public.moderation_log (
  id         bigint generated by default as identity primary key,
  actor_id   uuid,
  message_id bigint,
  action     text not null,
  reason     text,
  created_at timestamptz not null default now()
);

-- ---------- 6. 判权函数 ----------
-- 关键点：
--   * security definer + set search_path = ''，函数体内的表名一律写全，
--     避免调用方改 search_path 把表劫持掉；
--   * 只能查表，不能把 exists 直接写进 RLS 策略里 —— 策略里查 user_roles
--     会触发 user_roles 自己的策略，形成 42P17 无限递归。
create schema if not exists private;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select exists (
    select 1
    from public.user_roles
    where user_id = (select auth.uid())
      and role = 'admin'
  );
$fn$;

revoke all on function private.is_admin() from public;
grant usage on schema private to authenticated;
grant execute on function private.is_admin() to authenticated;

-- ---------- 7. 注册成功 → 自动建资料 ----------
-- 昵称优先取注册时填的 username（放进 raw_user_meta_data），
-- 没填就退回邮箱前缀；撞名或撞保留字自动加后缀，绝不让注册失败。
create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  raw_name   text;
  base_name  text;
  final_name text;
  tail       text;
begin
  tail := substr(replace(new.id::text, '-', ''), 1, 4);

  raw_name := coalesce(new.raw_user_meta_data ->> 'username', '');
  if btrim(raw_name) = '' then
    raw_name := split_part(coalesce(new.email, ''), '@', 1);
  end if;

  base_name := regexp_replace(raw_name, '[[:space:]]', '', 'g');
  base_name := regexp_replace(base_name, '[<>"&/\\;%*@]', '', 'g');
  base_name := btrim(left(base_name, 16));

  if char_length(base_name) < 3 then
    base_name := 'user_' || tail;
  end if;

  begin
    insert into public.profiles (id, username) values (new.id, base_name);
  exception when unique_violation or check_violation then
    -- 撞名或命中保留字（admin 之类）：加 4 位后缀再来一次
    final_name := left(base_name, 10) || '_' || tail;
    begin
      insert into public.profiles (id, username) values (new.id, final_name);
    exception when others then
      insert into public.profiles (id, username)
      values (new.id, 'user_' || substr(md5(random()::text), 1, 8));
    end;
  end;

  return new;
end;
$fn$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- ---------- 8. 资料更新时间 ----------
create or replace function private.touch_updated_at()
returns trigger
language plpgsql
as $fn$
begin
  new.updated_at := now();
  return new;
end;
$fn$;

drop trigger if exists profiles_touch_trg on public.profiles;
create trigger profiles_touch_trg
  before update on public.profiles
  for each row execute function private.touch_updated_at();

-- ---------- 9. 留言守卫 ----------
-- INSERT/UPDATE 全从这里过，客户端传什么 status 都不算数：
--   待审 → 站长放行前谁都看不到；信任用户直接发；发布后正文锁死。
create or replace function private.messages_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  prof public.profiles;
  hits integer;
  bad  text;
  hdrs jsonb;
begin
  select * into prof from public.profiles where id = new.author_id;
  if not found then
    raise exception '账号资料不存在，请重新登录后再试';
  end if;

  if tg_op = 'INSERT' then
    if prof.is_banned then
      raise exception '该账号已被限制发言';
    end if;

    -- 正文规整：去掉 \r，掐掉首尾空白（表上有 body = btrim(body) 的约束）
    new.body := btrim(replace(coalesce(new.body, ''), chr(13), ''));
    if new.body = '' then
      raise exception '留言内容不能为空';
    end if;
    if char_length(new.body) > 1000 then
      raise exception '留言最多 1000 字';
    end if;

    -- 限流：同一账号 10 分钟内最多 5 条（含已删除的，防删了再发）
    select count(*) into hits
    from public.messages
    where author_id = new.author_id
      and created_at > now() - interval '10 minutes';
    if hits >= 5 then
      raise exception '发言太频繁了，请过几分钟再来';
    end if;

    -- 敏感词：block 直接拒发，flag 只降级为待审
    select word into bad
    from public.banned_words
    where new.body ilike '%' || word || '%' and severity = 'block'
    limit 1;
    if bad is not null then
      raise exception '内容包含不允许发布的词语';
    end if;

    -- 信任用户和站长本人直接公开：站长不需要审自己
    -- （敏感词 flag 命中时下面还会再降回待审，这一条对站长同样生效）
    new.status := case
      when prof.trust_level >= 1 then 'published'
      when private.is_admin()    then 'published'
      else 'pending'
    end;

    select word into bad
    from public.banned_words
    where new.body ilike '%' || word || '%' and severity = 'flag'
    limit 1;
    if bad is not null then
      new.status := 'pending';
    end if;

    -- 审核/删除相关字段一律清空，不给客户端留后门
    new.created_at    := now();
    new.published_at  := case when new.status = 'published' then now() else null end;
    new.reviewed_by   := null;
    new.reviewed_at   := null;
    new.deleted_at    := null;
    new.deleted_by    := null;
    new.delete_reason := null;

    -- 风控信息：PostgREST 把请求头塞在 request.headers 里
    begin
      hdrs := coalesce(current_setting('request.headers', true), '{}')::jsonb;
      new.author_ip := nullif(split_part(coalesce(hdrs ->> 'x-forwarded-for', ''), ',', 1), '')::inet;
      new.author_ua := left(coalesce(hdrs ->> 'user-agent', ''), 300);
    exception when others then
      new.author_ip := null;
      new.author_ua := null;
    end;

    return new;
  end if;

  -- ---------- UPDATE ----------
  -- 发布后不能改正文：否则"先审过一条干净内容，再改成广告"就绕过了审核
  if new.body is distinct from old.body then
    raise exception '留言发布后不能修改正文';
  end if;
  if new.author_id is distinct from old.author_id then
    raise exception '不能更改留言作者';
  end if;

  if private.is_admin() then
    if new.status is distinct from old.status then
      new.reviewed_by := (select auth.uid());
      new.reviewed_at := now();
      new.published_at := case
        when new.status = 'published' then coalesce(old.published_at, now())
        else old.published_at
      end;
      if new.status = 'deleted' then
        new.deleted_at := now();
        new.deleted_by := (select auth.uid());
      end if;
    end if;
  else
    -- 本人只能撤回，撤回后不再公开，但正文留在库里备查
    if new.status is distinct from 'withdrawn' then
      raise exception '没有权限修改留言状态';
    end if;
    if old.status not in ('pending', 'published') then
      raise exception '该留言当前状态不能撤回';
    end if;
  end if;

  return new;
end;
$fn$;

drop trigger if exists messages_guard_trg on public.messages;
create trigger messages_guard_trg
  before insert or update on public.messages
  for each row execute function private.messages_guard();

-- ---------- 10. 站长操作（RPC） ----------
-- 为什么不直接把 UPDATE(trust_level) 授权给 authenticated：
-- 策略之间是 OR 关系，一旦"本人可改自己这一行"，再放开列权限就等于
-- 任何登录用户都能给自己发信任。提权/审核类操作只能走函数。
create or replace function public.gb_review(p_message_id bigint, p_action text)
returns text
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_status text;
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;

  v_status := case p_action
    when 'publish' then 'published'
    when 'reject'  then 'rejected'
    when 'delete'  then 'deleted'
    else null
  end;

  if v_status is null then
    raise exception '未知操作：%', p_action;
  end if;

  update public.messages set status = v_status where id = p_message_id;
  if not found then
    raise exception '留言不存在';
  end if;

  insert into public.moderation_log (actor_id, message_id, action)
  values ((select auth.uid()), p_message_id, p_action);

  return v_status;
end;
$fn$;

create or replace function public.gb_set_trust(p_user uuid, p_level smallint)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;
  if p_level not between 0 and 1 then
    raise exception '信任等级只能是 0 或 1';
  end if;

  update public.profiles set trust_level = p_level where id = p_user;
  if not found then
    raise exception '用户不存在';
  end if;

  insert into public.moderation_log (actor_id, action, reason)
  values ((select auth.uid()), 'trust', p_user::text || ' -> ' || p_level::text);
end;
$fn$;

create or replace function public.gb_set_ban(p_user uuid, p_banned boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;

  update public.profiles set is_banned = p_banned where id = p_user;
  if not found then
    raise exception '用户不存在';
  end if;

  insert into public.moderation_log (actor_id, action, reason)
  values ((select auth.uid()), case when p_banned then 'ban' else 'unban' end, p_user::text);
end;
$fn$;

