-- 说明：
--   · notices 表与 data/notices.json 的 items 结构一一对应
--     （id 锚点名 / date 日期 / tags 标签数组 / pin 置顶 / hidden 下架 /
--       title 标题 / body 段落数组），jsonb 存 tags、body，前端零改动消费。
--   · notices.js 已改为「Supabase 优先、JSON 兜底」：本表有数据就读表，
--     表空或查询失败自动回退 data/notices.json，不影响断网时的降级体验。
--   · downloads 表只允许匿名 insert（埋点上报），任何客户端角色都读不到、
--     改不了、删不掉；统计一律走 dl_stats()（内部判权）。
--   · 全部写操作（公告增删改）与统计读取都走 security definer RPC，
--     函数第一行判 private.is_admin() —— 绕过前端 curl 也会被拒绝。
-- ============================================================

-- ---------- 1. 公告表 ----------
create table if not exists public.notices (
  id         text        primary key,
  date       text        not null,
  tags       jsonb       not null default '[]'::jsonb,
  pin        boolean     not null default false,
  hidden     boolean     not null default false,
  title      text        not null,
  body       jsonb       not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint notices_date_chk    check (date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  constraint notices_title_len   check (char_length(title) between 1 and 200),
  constraint notices_tags_is_arr check (jsonb_typeof(tags) = 'array'),
  constraint notices_body_is_arr check (jsonb_typeof(body) = 'array')
);

create index if not exists notices_list_idx
  on public.notices (hidden, pin desc, date desc);

-- ---------- 2. 下载统计表 ----------
create table if not exists public.downloads (
  id   bigint generated by default as identity primary key,
  key  text        not null,
  kind text        not null default 'download',
  ts   timestamptz not null default now(),

  constraint downloads_key_len  check (char_length(key) between 1 and 120),
  constraint downloads_kind_len check (char_length(kind) between 1 and 40)
);

create index if not exists downloads_ts_idx  on public.downloads (ts desc);
create index if not exists downloads_key_idx on public.downloads (key, ts desc);

-- ---------- 3. 收回默认权限 + 重新授权 ----------
revoke all on table public.notices   from anon, authenticated;
revoke all on table public.downloads from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

-- 公告：匿名与登录用户可读（RLS 只放行未下架的）；写操作只走 RPC。
grant select on table public.notices to anon, authenticated;

-- 下载：匿名与登录用户可写入（埋点上报）；不开放任何读/改/删。
grant insert on table public.downloads to anon, authenticated;

-- identity 自增列：匿名插入也要能用序列（生成 id）
grant usage, select on sequence public.downloads_id_seq to anon, authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.notices   enable row level security;
alter table public.downloads enable row level security;

-- ---------- 4. 行级策略 ----------

-- 公告只读：任何人只看得到「未下架」的
drop policy if exists notices_read_public on public.notices;
create policy notices_read_public on public.notices
  for select to anon, authenticated
  using (not hidden);

-- downloads：不建任何 SELECT / UPDATE / DELETE 策略 = 客户端完全读不到、
-- 改不了、删不掉。insert 策略允许匿名上报（埋点是公开行为）。
drop policy if exists downloads_insert on public.downloads;
create policy downloads_insert on public.downloads
  for insert to anon, authenticated
  with check (true);

-- ---------- 5. 公告管理 RPC（仅站长） ----------

-- 后台列表：返回全部公告（含已下架），置顶在前
create or replace function public.notice_list_admin()
returns table (
  id text, date text, tags jsonb, pin boolean,
  hidden boolean, title text, body jsonb
)
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;

  return query
    select n.id, n.date, n.tags, n.pin, n.hidden, n.title, n.body
    from public.notices n
    order by n.pin desc, n.date desc, n.id;
end;
$fn$;

-- 发布 / 更新公告（upsert，按 id 覆盖）
create or replace function public.notice_save(
  p_id text, p_date text, p_tags jsonb, p_pin boolean,
  p_hidden boolean, p_title text, p_body jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;

  if p_id is null or btrim(p_id) = '' then
    raise exception '缺少公告 id（锚点名）';
  end if;
  if p_title is null or btrim(p_title) = '' then
    raise exception '标题不能为空';
  end if;

  insert into public.notices (id, date, tags, pin, hidden, title, body, updated_at)
  values (
    p_id,
    coalesce(nullif(p_date, ''), to_char(now(), 'YYYY-MM-DD')),
    coalesce(p_tags, '[]'::jsonb),
    coalesce(p_pin, false),
    coalesce(p_hidden, false),
    btrim(p_title),
    coalesce(p_body, '[]'::jsonb),
    now()
  )
  on conflict (id) do update set
    date       = excluded.date,
    tags       = excluded.tags,
    pin        = excluded.pin,
    hidden     = excluded.hidden,
    title      = excluded.title,
    body       = excluded.body,
    updated_at = now();

  insert into public.moderation_log (actor_id, action, reason)
  values ((select auth.uid()), 'notice_save', p_id);
end;
$fn$;

-- 彻底删除公告（物理删；只想临时下架用 notice_save 把 hidden 置 true）
create or replace function public.notice_delete(p_id text)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;

  delete from public.notices where id = p_id;
  if not found then
    raise exception '公告不存在';
  end if;

  insert into public.moderation_log (actor_id, action, reason)
  values ((select auth.uid()), 'notice_delete', p_id);
end;
$fn$;

-- ---------- 6. 下载埋点 + 统计 RPC ----------

-- 埋点上报：匿名可调，只插入一条下载记录。
-- 防刷说明：纯前端埋点防不了伪造，这里只做 key/kind 长度约束；
--           前端用 sessionStorage 做同一 key 的短时去重（轻量缓解）。
create or replace function public.dl_record(p_key text, p_kind text)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if p_key is null or btrim(p_key) = '' then
    return;  -- 无标识的记录直接丢弃，不留垃圾行
  end if;

  insert into public.downloads (key, kind)
  values (
    left(btrim(p_key), 120),
    left(coalesce(nullif(btrim(p_kind), ''), 'download'), 40)
  );
end;
$fn$;

-- 统计看板（仅站长）：总量 + 按软件/类型排行 + 近 30 天按日趋势
create or replace function public.dl_stats()
returns json
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_total bigint;
  v_top   json;
  v_days  json;
begin
  if not private.is_admin() then
    raise exception '仅站长可以执行该操作';
  end if;

  select count(*) into v_total from public.downloads;

  select coalesce(json_agg(t order by t.cnt desc, t.key), '[]'::json)
  into v_top
  from (
    select key, kind, count(*) as cnt
    from public.downloads
    group by key, kind
    order by cnt desc
    limit 50
  ) t;

  select coalesce(json_agg(d order by d.day), '[]'::json)
  into v_days
  from (
    select to_char(date_trunc('day', ts), 'YYYY-MM-DD') as day,
           count(*) as cnt
    from public.downloads
    where ts >= now() - interval '30 days'
    group by 1
  ) d;

  return json_build_object('total', v_total, 'top', v_top, 'days', v_days);
end;
$fn$;

-- ---------- 7. RPC 执行权 ----------
-- 函数默认对 PUBLIC 开 EXECUTE，必须显式收回。
revoke all on function public.notice_list_admin() from public, anon;
revoke all on function public.notice_save(text, text, jsonb, boolean, boolean, text, jsonb) from public, anon;
revoke all on function public.notice_delete(text) from public, anon;
revoke all on function public.dl_stats() from public, anon;
revoke all on function public.dl_record(text, text) from public, anon;

-- 公告管理 + 统计：仅登录用户（函数内部再判站长）
grant execute on function public.notice_list_admin() to authenticated;
grant execute on function public.notice_save(text, text, jsonb, boolean, boolean, text, jsonb) to authenticated;
grant execute on function public.notice_delete(text) to authenticated;
grant execute on function public.dl_stats() to authenticated;

-- 下载埋点：匿名与登录都可上报
grant execute on function public.dl_record(text, text) to anon, authenticated;

notify pgrst, 'reload schema';

